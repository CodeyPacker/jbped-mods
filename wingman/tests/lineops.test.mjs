import assert from "node:assert/strict";
const L = await import("../mods/wingman/lineops.js");
const { body } = await import("../mods/wingman/edit.js");
const lines = (...a) => a.map((x, i) => (i < a.length - 1 ? x + "\n" : x + "\n"));
// apply an op to plain text the simple way
const apply = (ls, op) => {
  const t = ls.map(body);
  const head = t.slice(0, op.from.line).concat(t[op.from.line].slice(0, op.from.col)).join("\n");
  const tail = [t[op.to.line].slice(op.to.col)].concat(t.slice(op.to.line + 1)).join("\n");
  return (head + op.text + tail).split("\n");
};
const F = lines("a", "b", "c", "d");
const c = { line: 1, col: 0 };
assert.deepEqual(apply(F, L.moveLines(F, 1, 1, -1, null, c)), ["b", "a", "c", "d"]);
assert.deepEqual(apply(F, L.moveLines(F, 1, 2, 1, null, c)), ["a", "d", "b", "c"]);
assert.equal(L.moveLines(F, 0, 0, -1, null, c), null);
assert.equal(L.moveLines(F, 3, 3, 1, null, c), null);
assert.deepEqual(L.moveLines(F, 1, 1, 1, null, c).cur, { line: 2, col: 0 });
assert.deepEqual(apply(F, L.copyLines(F, 1, 2, 1, null, c)), ["a", "b", "c", "b", "c", "d"]);
assert.deepEqual(L.copyLines(F, 1, 2, 1, null, c).cur, { line: 3, col: 0 });
assert.deepEqual(L.copyLines(F, 1, 2, -1, null, c).cur, c);
assert.deepEqual(apply(F, L.deleteLines(F, 1, 2, c)), ["a", "d"]);
assert.deepEqual(apply(F, L.deleteLines(F, 3, 3, c)), ["a", "b", "c"]);
assert.deepEqual(apply(F, L.deleteLines(F, 0, 3, c)), [""]);
const J = lines("foo(", "  x,", "  y", ")");
assert.deepEqual(apply(J, L.joinLines(J, 0, 3)), ["foo(x, y)"]);
assert.deepEqual(apply(J, L.joinLines(J, 1, 1)), ["foo(", "  x, y", ")"]);
assert.deepEqual(L.lineSpan({ line: 1, col: 2 }, { line: 3, col: 0 }), [1, 2]);
assert.deepEqual(L.lineSpan(null, { line: 2, col: 1 }), [2, 2]);
const C = lines("  if (x) {", "    y();", "", "  }");
const on = L.toggleComment(C, 0, 3, "//", null, { line: 1, col: 4 });
assert.deepEqual(apply(C, on), ["  // if (x) {", "  //   y();", "", "  // }"]);
assert.deepEqual(on.cur, { line: 1, col: 7 });
const C2 = apply(C, on).map((x) => x + "\n");
const off = L.toggleComment(C2, 0, 3, "//", null, { line: 1, col: 7 });
assert.deepEqual(apply(C2, off), ["  if (x) {", "    y();", "", "  }"]);
assert.deepEqual(off.cur, { line: 1, col: 4 });
const H = lines("<p>x</p>");
const h = L.toggleComment(H, 0, 0, ["<!--", "-->"], null, { line: 0, col: 0 });
assert.deepEqual(apply(H, h), ["<!-- <p>x</p> -->"]);
assert.deepEqual(apply(apply(H, h).map((x) => x + "\n"), L.toggleComment(apply(H, h).map((x) => x + "\n"), 0, 0, ["<!--", "-->"], null, { line: 0, col: 0 })), ["<p>x</p>"]);
assert.equal(L.commentFor("src/a.ts"), "//");
assert.equal(L.commentFor("Dockerfile"), "#");
assert.equal(L.commentFor("x.unknownext"), null);
console.log("lineops tests pass");
